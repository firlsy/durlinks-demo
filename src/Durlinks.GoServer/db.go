// columnExists 兼容 SQLite PRAGMA 与 PG information_schema。
func (d *DB) columnExists(table, column string) bool {
	if d.pg {
		var n int
		// pgx 只认 $n 占位符，这里必须走 Rebind，否则查询必失败、迁移会每次重复执行
		err := d.sql.QueryRow(d.Rebind(`SELECT COUNT(*) FROM information_schema.columns WHERE lower(table_name)=lower(?) AND lower(column_name)=lower(?)`), table, column).Scan(&n)
		return err == nil && n > 0
	}
	rows, err := d.sql.Query(`PRAGMA table_info("` + table + `")`)
	if err != nil {
		return false
	}
	defer rows.Close()
	for rows.Next() {
		var (
			cid     int
			name    string
			ctype   string
			notnull int
			dflt    any
			pk      int
		)
		if err := rows.Scan(&cid, &name, &ctype, &notnull, &dflt, &pk); err == nil {
			if strings.EqualFold(name, column) {
				return true
			}
		}
	}
	return false
}

func (d *DB) execIgnore(sqlText string) {
	_, _ = d.sql.Exec(d.Rebind(sqlText))
}

// execArgs 参数化执行（自动按方言改写占位符），任何带外部值/库内文本的语句都该走这里。
func (d *DB) execArgs(sqlText string, args ...any) {
	_, _ = d.sql.Exec(d.Rebind(sqlText), args...)
}

// migrate 补齐老库缺的列/表，等价于 SchemaUpgrader。
func (d *DB) migrate() error {
	// TokenVersion：改密码后作废旧 JWT 用
	if !d.columnExists("Users", "TokenVersion") {
		d.execIgnore(`ALTER TABLE "Users" ADD COLUMN "TokenVersion" INTEGER NOT NULL DEFAULT 0`)
	}
	if !d.columnExists("Links", "LibraryId") {
		if _, err := d.sql.Exec(`ALTER TABLE "Links" ADD COLUMN "LibraryId" INTEGER NULL`); err != nil &&
			!strings.Contains(strings.ToLower(err.Error()), "duplicate") {
			return err
		}
	}
	if !d.columnExists("LlmConfigs", "Name") {
		d.execIgnore(`ALTER TABLE "LlmConfigs" ADD COLUMN "Name" TEXT NOT NULL DEFAULT ''`)
	}
	if !d.columnExists("LlmConfigs", "IsDefault") {
		// PostgreSQL 的布尔列必须用 boolean，写成 INTEGER 会让 pgx 写入时类型不匹配
		if d.pg {
			d.execIgnore(`ALTER TABLE "LlmConfigs" ADD COLUMN "IsDefault" boolean NOT NULL DEFAULT FALSE`)
		} else {
			d.execIgnore(`ALTER TABLE "LlmConfigs" ADD COLUMN "IsDefault" INTEGER NOT NULL DEFAULT 0`)
		}
	}
	if !d.columnExists("LlmConfigs", "Protocol") {
		d.execIgnore(`ALTER TABLE "LlmConfigs" ADD COLUMN "Protocol" TEXT NOT NULL DEFAULT 'openai'`)
	}
	if !d.columnExists("LlmConfigs", "ModelsJson") {
		d.execIgnore(`ALTER TABLE "LlmConfigs" ADD COLUMN "ModelsJson" TEXT NOT NULL DEFAULT ''`)
	}
	if !d.columnExists("LlmConfigs", "RetryPolicy") {
		d.execIgnore(`ALTER TABLE "LlmConfigs" ADD COLUMN "RetryPolicy" TEXT NOT NULL DEFAULT 'default'`)
	}
	if !d.columnExists("LlmConfigs", "MaxRetries") {
		d.execIgnore(`ALTER TABLE "LlmConfigs" ADD COLUMN "MaxRetries" INTEGER NOT NULL DEFAULT 8`)
	}
	if !d.columnExists("LlmConfigs", "RetryOn") {
		d.execIgnore(`ALTER TABLE "LlmConfigs" ADD COLUMN "RetryOn" TEXT NOT NULL DEFAULT 'empty,rate_limit,server,timeout,network'`)
	}
	d.execIgnore(`UPDATE "LlmConfigs" SET "Name" = '默认配置' WHERE "Name" = ''`)
	d.execIgnore(`UPDATE "LlmConfigs" SET "ModelsJson" = '["' || "Model" || '"]' WHERE "ModelsJson" = '' AND "Model" <> ''`)
	return nil
}

// seed 首次启动：默认发布库、未归类链接归库、admin 账号、默认 LLM 配置、分类字典回填。
func (d *DB) seed(logf func(string, ...any)) error {
	// 1) 至少一个发布库
	var libCount int
	if err := d.sql.QueryRow(`SELECT COUNT(*) FROM "PublishLibraries"`).Scan(&libCount); err != nil {
		return err
	}
	var libID int
	if libCount == 0 {
		if d.pg {
			err := d.sql.QueryRow(d.Rebind(`INSERT INTO "PublishLibraries" ("Name","Description","VisibleOnWeb","VisibleOnClient","SortOrder","IsDeleted","CreatedAt") VALUES (?,?,?,?,?,?,?) RETURNING "Id"`),
				"默认发布库", "系统初始化创建，可在发布管理中改名", d.BoolValue(true), d.BoolValue(true), 0, d.BoolValue(false), time.Now().UTC()).Scan(&libID)
			if err != nil {
				return err
			}
		} else {
			res, err := d.sql.Exec(`INSERT INTO "PublishLibraries" ("Name","Description","VisibleOnWeb","VisibleOnClient","SortOrder","IsDeleted","CreatedAt") VALUES (?,?,?,?,?,?,?)`,
				"默认发布库", "系统初始化创建，可在发布管理中改名", 1, 1, 0, 0, time.Now().UTC().Format(time.RFC3339Nano))
			if err != nil {
				return err
			}
			id, _ := res.LastInsertId()
			libID = int(id)
		}
		logf("已创建默认发布库 Id=%d", libID)
	} else {
		if err := d.sql.QueryRow(`SELECT "Id" FROM "PublishLibraries" ORDER BY "SortOrder", "Id" LIMIT 1`).Scan(&libID); err != nil {
			// 取不到库 id 时不能继续：下面的 UPDATE 会把未归类链接的 LibraryId 写成 0（指向不存在的库）
			return fmt.Errorf("读取默认发布库失败: %w", err)
		}
	}

	// 2) 未归类链接归入默认库
	if libID <= 0 {
		return fmt.Errorf("默认发布库 Id 非法(%d)，已中止归库", libID)
	}
	res, err := d.sql.Exec(d.Rebind(`UPDATE "Links" SET "LibraryId" = ? WHERE "LibraryId" IS NULL`), libID)
	if err == nil {
		if n, _ := res.RowsAffected(); n > 0 {
			logf("已将 %d 条未归类链接归入默认发布库", n)
		}
	}

	// 3) 默认管理员：admin / $DURLINKS_ADMIN_PASSWORD，缺省 admin123
	var userCount int
	if err := d.sql.QueryRow(`SELECT COUNT(*) FROM "Users"`).Scan(&userCount); err != nil {
		return err
	}
	adminPwd := os.Getenv("DURLINKS_ADMIN_PASSWORD")
	if adminPwd == "" {
		adminPwd = "admin123"
	}
	if userCount == 0 {
		hash := HashPassword(adminPwd)
		if _, err := d.sql.Exec(d.Rebind(`INSERT INTO "Users" ("Username","PasswordHash","Role","MfaSecret","MfaEnabled","CreatedAt") VALUES (?,?,?,?,?,?)`),
			"admin", hash, int(RoleSuperAdmin), nil, d.BoolValue(false), d.now()); err != nil {
			return err
		}
		if os.Getenv("DURLINKS_ADMIN_PASSWORD") == "" {
			logf("已创建默认管理员账号 admin（口令取自内置默认值，仅限本地开发）；生产环境请设置 DURLINKS_ADMIN_PASSWORD 环境变量后重建数据库")
		} else {
			logf("已创建管理员账号 admin（口令取自 DURLINKS_ADMIN_PASSWORD）")
		}
	}

	// 4) LLM 配置至少一条
	var llmCount int
	if err := d.sql.QueryRow(`SELECT COUNT(*) FROM "LlmConfigs"`).Scan(&llmCount); err != nil {
		return err
	}
	if llmCount == 0 {
		_, err := d.sql.Exec(d.Rebind(`INSERT INTO "LlmConfigs"
			("Name","Protocol","RetryPolicy","MaxRetries","RetryOn","ApiEndpoint","ApiKey","Model","ModelsJson","IsConfigured","IsDefault","UpdatedAt")
			VALUES (?,?,?,?,?,?,?,?,?,?,?,?)`),
			"默认配置", "openai", "default", 8, "empty,rate_limit,server,timeout,network", "", "", "", "", d.BoolValue(false), d.BoolValue(true), d.now())
		if err != nil {
			return err
		}
	} else {
		var defaults int
		_ = d.sql.QueryRow(`SELECT COUNT(*) FROM "LlmConfigs" WHERE "IsDefault" = ` + d.True()).Scan(&defaults)
		if defaults == 0 {
			d.execIgnore(`UPDATE "LlmConfigs" SET "IsDefault" = ` + d.True() + ` WHERE "Id" = (SELECT MIN("Id") FROM "LlmConfigs")`)
		}
	}

	// 5) 分类字典回填（分组/平台/链接形式/标签）
	if err := d.backfillCategories(); err != nil {
		return err
	}
	return nil
}

func (d *DB) now() any {
	if d.pg {
		return time.Now().UTC()
	}
	return time.Now().UTC().Format(time.RFC3339Nano)
}

func (d *DB) backfillCategories() error {
	// 分组
	d.execIgnore(`INSERT INTO "Groups" ("Name") SELECT DISTINCT TRIM("GroupName") FROM "Links"
		WHERE TRIM("GroupName") <> '' AND TRIM("GroupName") NOT IN (SELECT "Name" FROM "Groups")`)

	// 平台：拆逗号原子项
	rows, err := d.sql.Query(`SELECT DISTINCT "Platform" FROM "Links" WHERE "Platform" IS NOT NULL AND "Platform" <> ''`)
	if err != nil {
		return err
	}
	var platforms []string
	for rows.Next() {
		var p sql.NullString
		if err := rows.Scan(&p); err == nil && p.Valid {
			platforms = append(platforms, p.String)
		}
	}
	rows.Close()
	seen := map[string]bool{}
	for _, raw := range platforms {
		for _, part := range strings.Split(raw, ",") {
			name := strings.TrimSpace(part)
			if name == "" || seen[name] {
				continue
			}
			seen[name] = true
			var exists int
			_ = d.sql.QueryRow(d.Rebind(`SELECT COUNT(*) FROM "Platforms" WHERE "Name" = ?`), name).Scan(&exists)
			if exists == 0 {
				d.execArgs(`INSERT INTO "Platforms" ("Name") VALUES (?)`, name)
			}
		}
	}

	// 链接形式：内置四类 + 历史值
	builtin := []string{"下载直链", "官网/普通网址", "网盘", "磁力"}
	for _, name := range builtin {
		var exists int
		_ = d.sql.QueryRow(d.Rebind(`SELECT COUNT(*) FROM "LinkTypes" WHERE "Name" = ?`), name).Scan(&exists)
		if exists == 0 {
			d.execArgs(`INSERT INTO "LinkTypes" ("Name") VALUES (?)`, name)
		}
	}
	rows2, err := d.sql.Query(`SELECT DISTINCT "LinkType" FROM "Links" WHERE "LinkType" IS NOT NULL AND "LinkType" <> ''`)
	if err != nil {
		return err
	}
	var types []string
	for rows2.Next() {
		var t sql.NullString
		if err := rows2.Scan(&t); err == nil && t.Valid {
			types = append(types, strings.TrimSpace(t.String))
		}
	}
	rows2.Close()
	for _, name := range types {
		if name == "" {
			continue
		}
		var exists int
		_ = d.sql.QueryRow(d.Rebind(`SELECT COUNT(*) FROM "LinkTypes" WHERE "Name" = ?`), name).Scan(&exists)
		if exists == 0 {
			d.execArgs(`INSERT INTO "LinkTypes" ("Name") VALUES (?)`, name)
		}
	}

	// 标签：把已挂在链接上的标签补进字典
	rows3, err := d.sql.Query(`SELECT DISTINCT tg."Name" FROM "LinkTags" lt JOIN "Tags" tg ON tg."Id" = lt."TagId"`)
	if err != nil {
		return nil
	}
	var tagNames []string
	for rows3.Next() {
		var n string
		if err := rows3.Scan(&n); err == nil {
			tagNames = append(tagNames, n)
		}
	}
	rows3.Close()
	for _, n := range tagNames {
		if strings.TrimSpace(n) == "" {
			continue
		}
		var exists int
		_ = d.sql.QueryRow(d.Rebind(`SELECT COUNT(*) FROM "Tags" WHERE "Name" = ?`), n).Scan(&exists)
		if exists == 0 {
			d.execArgs(`INSERT INTO "Tags" ("Name") VALUES (?)`, n)
		}
	}
	return nil
}
