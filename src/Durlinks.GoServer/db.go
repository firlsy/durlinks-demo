// Init 建表（幂等）、补列、回填字典、种子数据。等价于 EnsureCreated + SchemaUpgrader + DbInitializer。
func (d *DB) Init(logf func(string, ...any)) error {
	for _, stmt := range d.schemaStatements() {
		if _, err := d.sql.Exec(stmt); err != nil {
			return fmt.Errorf("建表失败: %w\nSQL: %s", err, stmt)
		}
	}
	if err := d.migrate(); err != nil {
		return err
	}
	return d.seed(logf)
}

