// DB 包装 database/sql，屏蔽 SQLite / PostgreSQL 的方言差异。
type DB struct {
	sql *sql.DB
	pg  bool
}

func (d *DB) IsPostgres() bool { return d.pg }

// Rebind 把 ? 占位符转成 PostgreSQL 的 $1..$n；SQLite 原样返回。
func (d *DB) Rebind(q string) string {
	if !d.pg {
		return q
	}
	var b strings.Builder
	n := 0
	for _, r := range q {
		if r == '?' {
			n++
			b.WriteString("$")
			b.WriteString(strconv.Itoa(n))
			continue
		}
		b.WriteRune(r)
	}
	return b.String()
}

// BoolValue 把 bool 转成当前方言接受的值（SQLite 用 0/1，PG 用 bool）。
func (d *DB) BoolValue(v bool) any {
	if d.pg {
		return v
	}
	if v {
		return 1
	}
	return 0
}

// False / True 用于 SQL 文本里的布尔字面量。
func (d *DB) False() string {
	if d.pg {
		return "false"
	}
	return "0"
}

func (d *DB) True() string {
	if d.pg {
		return "true"
	}
	return "1"
}

func OpenDB(cfg *Config, baseDir string) (*DB, error) {
	var (
		driver string
		dsn    string
		pg     bool
	)
	if cfg.Database.Provider == "postgres" {
		if strings.TrimSpace(cfg.ConnectionStrings.Postgres) == "" {
			return nil, fmt.Errorf("使用 PostgreSQL 时必须配置 ConnectionStrings:Postgres")
		}
		driver, dsn, pg = "pgx", cfg.ConnectionStrings.Postgres, true
	} else {
		dbPath := ResolvePath(baseDir, cfg.Database.Path)
		if err := os.MkdirAll(filepath.Dir(dbPath), 0o755); err != nil {
			return nil, err
		}
		driver = "sqlite"
		dsn = "file:" + filepath.ToSlash(dbPath) + "?_pragma=busy_timeout(8000)&_pragma=journal_mode(WAL)&_pragma=foreign_keys(1)&_pragma=synchronous(NORMAL)"
	}

	conn, err := sql.Open(driver, dsn)
	if err != nil {
		return nil, err
	}
	if !pg {
		// SQLite 单写者：串行化连接，避免 database is locked
		conn.SetMaxOpenConns(1)
	} else {
		conn.SetMaxOpenConns(16)
	}
	conn.SetMaxIdleConns(4)
	conn.SetConnMaxLifetime(time.Hour)
	if err := conn.Ping(); err != nil {
		return nil, err
	}
	return &DB{sql: conn, pg: pg}, nil
}

func (d *DB) Close() error { return d.sql.Close() }

