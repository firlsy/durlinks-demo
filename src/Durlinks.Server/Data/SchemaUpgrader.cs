using Durlinks.Shared.Entities;
using Microsoft.EntityFrameworkCore;

namespace Durlinks.Server.Data;

/// <summary>
/// 轻量 schema 升级：项目用 EnsureCreated（不跑 Migration），新增表/列在已有库上不会自动生效。
/// 这里按 provider 手动补表补列，并把历史链接归入默认发布库。可重复执行（幂等）。
/// </summary>
public static class SchemaUpgrader
{
    public static void Upgrade(AppDbContext db, ILogger? logger = null)
    {
        var isPg = db.Database.ProviderName?.Contains("Npgsql", StringComparison.OrdinalIgnoreCase) == true;
        try
        {
            if (isPg)
            {
                Exec(db, """
                    CREATE TABLE IF NOT EXISTS "PublishLibraries" (
                        "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        "Name" character varying(200) NOT NULL,
                        "Description" text NULL,
                        "VisibleOnWeb" boolean NOT NULL DEFAULT TRUE,
                        "VisibleOnClient" boolean NOT NULL DEFAULT TRUE,
                        "SortOrder" integer NOT NULL DEFAULT 0,
                        "IsDeleted" boolean NOT NULL DEFAULT FALSE,
                        "CreatedAt" timestamp with time zone NOT NULL DEFAULT NOW()
                    )
                    """);
                if (!ColumnExists(db, "Links", "LibraryId"))
                    TryAddLibraryColumn(db, "ALTER TABLE \"Links\" ADD COLUMN \"LibraryId\" integer NULL");
                Exec(db, "CREATE INDEX IF NOT EXISTS \"IX_Links_LibraryId\" ON \"Links\" (\"LibraryId\")");
                Exec(db, "CREATE INDEX IF NOT EXISTS \"IX_PublishLibraries_IsDeleted\" ON \"PublishLibraries\" (\"IsDeleted\")");
                Exec(db, "CREATE INDEX IF NOT EXISTS \"IX_PublishLibraries_SortOrder\" ON \"PublishLibraries\" (\"SortOrder\")");
            }
            else
            {
                Exec(db, """
                    CREATE TABLE IF NOT EXISTS "PublishLibraries" (
                        "Id" INTEGER NOT NULL CONSTRAINT "PK_PublishLibraries" PRIMARY KEY AUTOINCREMENT,
                        "Name" TEXT NOT NULL,
                        "Description" TEXT NULL,
                        "VisibleOnWeb" INTEGER NOT NULL DEFAULT 1,
                        "VisibleOnClient" INTEGER NOT NULL DEFAULT 1,
                        "SortOrder" INTEGER NOT NULL DEFAULT 0,
                        "IsDeleted" INTEGER NOT NULL DEFAULT 0,
                        "CreatedAt" TEXT NOT NULL
                    )
                    """);
                if (!ColumnExists(db, "Links", "LibraryId"))
                    TryAddLibraryColumn(db, "ALTER TABLE \"Links\" ADD COLUMN \"LibraryId\" INTEGER NULL");
                Exec(db, "CREATE INDEX IF NOT EXISTS \"IX_Links_LibraryId\" ON \"Links\" (\"LibraryId\")");
            }

            EnsureDefaultLibrary(db, logger);
            EnsureCategoryTables(db, isPg, logger);
            NormalizePlatforms(db, logger);
            UpgradeLlmConfigs(db, isPg, logger);
        }
        catch (Exception ex)
        {
            logger?.LogError(ex, "schema 升级失败（发布库）");
            throw;
        }
    }

    /// <summary>补齐分类管理使用的表，并从历史链接中回填唯一分组名称。</summary>
    private static void EnsureCategoryTables(AppDbContext db, bool isPg, ILogger? logger)
    {
        if (isPg)
        {
            Exec(db, "CREATE TABLE IF NOT EXISTS \"Groups\" (\"Id\" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \"Name\" character varying(200) NOT NULL)");
            Exec(db, "CREATE UNIQUE INDEX IF NOT EXISTS \"IX_Groups_Name\" ON \"Groups\" (\"Name\")");
            Exec(db, "CREATE TABLE IF NOT EXISTS \"Platforms\" (\"Id\" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \"Name\" character varying(200) NOT NULL)");
            Exec(db, "CREATE UNIQUE INDEX IF NOT EXISTS \"IX_Platforms_Name\" ON \"Platforms\" (\"Name\")");
            Exec(db, "CREATE TABLE IF NOT EXISTS \"Tags\" (\"Id\" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \"Name\" character varying(200) NOT NULL)");
            Exec(db, "CREATE UNIQUE INDEX IF NOT EXISTS \"IX_Tags_Name\" ON \"Tags\" (\"Name\")");
            Exec(db, "CREATE TABLE IF NOT EXISTS \"LinkTypes\" (\"Id\" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \"Name\" character varying(200) NOT NULL)");
            Exec(db, "CREATE UNIQUE INDEX IF NOT EXISTS \"IX_LinkTypes_Name\" ON \"LinkTypes\" (\"Name\")");
        }
        else
        {
            Exec(db, "CREATE TABLE IF NOT EXISTS \"Groups\" (\"Id\" INTEGER NOT NULL CONSTRAINT \"PK_Groups\" PRIMARY KEY AUTOINCREMENT, \"Name\" TEXT NOT NULL)");
            Exec(db, "CREATE UNIQUE INDEX IF NOT EXISTS \"IX_Groups_Name\" ON \"Groups\" (\"Name\")");
            Exec(db, "CREATE TABLE IF NOT EXISTS \"Platforms\" (\"Id\" INTEGER NOT NULL CONSTRAINT \"PK_Platforms\" PRIMARY KEY AUTOINCREMENT, \"Name\" TEXT NOT NULL)");
            Exec(db, "CREATE UNIQUE INDEX IF NOT EXISTS \"IX_Platforms_Name\" ON \"Platforms\" (\"Name\")");
            Exec(db, "CREATE TABLE IF NOT EXISTS \"Tags\" (\"Id\" INTEGER NOT NULL CONSTRAINT \"PK_Tags\" PRIMARY KEY AUTOINCREMENT, \"Name\" TEXT NOT NULL)");
            Exec(db, "CREATE UNIQUE INDEX IF NOT EXISTS \"IX_Tags_Name\" ON \"Tags\" (\"Name\")");
            Exec(db, "CREATE TABLE IF NOT EXISTS \"LinkTypes\" (\"Id\" INTEGER NOT NULL CONSTRAINT \"PK_LinkTypes\" PRIMARY KEY AUTOINCREMENT, \"Name\" TEXT NOT NULL)");
            Exec(db, "CREATE UNIQUE INDEX IF NOT EXISTS \"IX_LinkTypes_Name\" ON \"LinkTypes\" (\"Name\")");
        }

        // 把历史自由文本分组/平台同步到字典；对重复名称使用 NOT EXISTS 保证可重复执行。
        Exec(db, "INSERT INTO \"Groups\" (\"Name\") SELECT DISTINCT TRIM(\"GroupName\") FROM \"Links\" WHERE TRIM(\"GroupName\") <> '' AND NOT EXISTS (SELECT 1 FROM \"Groups\" g WHERE g.\"Name\" = TRIM(\"Links\".\"GroupName\"))");
        // 平台字段可能是逗号分隔多值：在内存里拆成原子项再回填，避免把组合串写进字典
        var platformBackfill = db.Links.AsNoTracking().Where(x => x.Platform != null && x.Platform != "")
            .Select(x => x.Platform!).ToList()
            .SelectMany(p => p.Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
            .Where(x => x.Length > 0).Distinct(StringComparer.Ordinal).ToList();
        var dictPlatforms = db.Platforms.Select(x => x.Name).ToHashSet(StringComparer.Ordinal);
        foreach (var p in platformBackfill.Where(x => !dictPlatforms.Contains(x)))
            db.Platforms.Add(new PlatformOption { Name = p });
        db.SaveChanges();
        // 链接形式字典：内置 4 类 + 历史链接里出现过的其他值
        var linkTypeNames = Durlinks.Shared.Enums.LinkTypes.All.ToList();
        linkTypeNames.AddRange(db.Links.AsNoTracking().Where(x => x.LinkType != null && x.LinkType != "")
            .Select(x => x.LinkType!).ToList());
        var dictTypes = db.LinkTypes.Select(x => x.Name).ToHashSet(StringComparer.Ordinal);
        foreach (var name in linkTypeNames.Where(x => !string.IsNullOrWhiteSpace(x) && !dictTypes.Contains(x.Trim()))
                     .Select(x => x.Trim()).Distinct(StringComparer.Ordinal))
            db.LinkTypes.Add(new LinkTypeOption { Name = name });
        db.SaveChanges();

        var existingTags = db.Tags.AsNoTracking().Select(x => x.Name).ToList().ToHashSet(StringComparer.OrdinalIgnoreCase);
        var linkTags = db.LinkTags.Include(x => x.Tag).AsNoTracking().Select(x => x.Tag.Name).Distinct().ToList();
        foreach (var name in linkTags.Where(x => !string.IsNullOrWhiteSpace(x) && existingTags.Add(x.Trim()))) db.Tags.Add(new Tag { Name = name.Trim() });
        db.SaveChanges();
        logger?.LogInformation("分类管理字典表已就绪");
    }

    /// <summary>
    /// 把历史"平台"组合名（Android/iOS/Mac）拆成逗号分隔的多值，并把 Platforms 字典重建为原子项。
    /// 幂等：已是逗号分隔或原子值时保持不变。
    /// </summary>
    private static void NormalizePlatforms(AppDbContext db, ILogger? logger)
    {
        // 读取所有非空平台（列表里 in-memory 判断，避免 DB 端 Contains 的 provider 差异）
        var allWithPlatform = db.Links.Where(x => x.Platform != null).Select(x => new { x.Id, x.Platform }).ToList();
        var alias = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)
        { ["MacOS"] = "Mac", ["win32"] = "Windows", ["win64"] = "Windows" };
        var changed = new List<(int Id, string Value)>();
        foreach (var row in allWithPlatform)
        {
            var raw = row.Platform!;
            var parts = raw.Split('/', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
                .Select(p => alias.TryGetValue(p, out var v) ? v : p)
                .Where(x => x.Length > 0).Distinct(StringComparer.Ordinal).ToList();
            var normalized = string.Join(", ", parts);
            if (normalized != raw) changed.Add((row.Id, normalized));
        }
        if (changed.Count > 0)
        {
            var idSet = changed.Select(x => x.Id).ToHashSet();
            var valueMap = changed.ToDictionary(x => x.Id, x => x.Value);
            foreach (var entity in db.Links.Where(x => idSet.Contains(x.Id)).ToList())
                entity.Platform = valueMap[entity.Id];
            db.SaveChanges();
        }

        // 字典：删掉含斜杠的旧组合项与别名项（无链接引用了），补回所有链接里出现过的原子值
        var stale = db.Platforms.ToList().Where(n => n.Name.Contains("/") || n.Name.Contains(",") || alias.ContainsKey(n.Name)).ToList();
        if (stale.Count > 0) { db.Platforms.RemoveRange(stale); db.SaveChanges(); }

        var atoms = db.Links.AsNoTracking().Where(x => x.Platform != null && x.Platform != "")
            .Select(x => x.Platform!).ToList()
            .SelectMany(p => p.Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
            .Where(x => x.Length > 0).Distinct(StringComparer.Ordinal).ToList();
        var existing = db.Platforms.Select(x => x.Name).ToHashSet(StringComparer.Ordinal);
        foreach (var atom in atoms.Where(x => !existing.Contains(x))) db.Platforms.Add(new PlatformOption { Name = atom });
        if (atoms.Count > 0) db.SaveChanges();
        if (changed.Count > 0 || stale.Count > 0)
            logger?.LogInformation("平台组合名已拆分为 {Count} 个原子平台", atoms.Count);
    }

    /// <summary>保证至少有一个发布库，并把未归类链接归入它。</summary>
    private static void EnsureDefaultLibrary(AppDbContext db, ILogger? logger)
    {
        var lib = db.PublishLibraries.OrderBy(x => x.SortOrder).ThenBy(x => x.Id).FirstOrDefault();
        if (lib is null)
        {
            lib = new PublishLibrary
            {
                Name = "默认发布库",
                Description = "系统初始化创建，可在发布管理中改名",
                VisibleOnWeb = true,
                VisibleOnClient = true,
                SortOrder = 0
            };
            db.PublishLibraries.Add(lib);
            db.SaveChanges();
            logger?.LogInformation("已创建默认发布库 Id={Id}", lib.Id);
        }

        var orphans = db.Links.Where(x => x.LibraryId == null).ToList();
        if (orphans.Count > 0)
        {
            foreach (var l in orphans) l.LibraryId = lib.Id;
            db.SaveChanges();
            logger?.LogInformation("已将 {Count} 条未归类链接归入默认发布库", orphans.Count);
        }
    }

    /// <summary>LLM 配置支持多条：补 Name/IsDefault 列，并保证恰好有一条默认配置。</summary>
    private static void UpgradeLlmConfigs(AppDbContext db, bool isPg, ILogger? logger)
    {
        if (!ColumnExists(db, "LlmConfigs", "Name"))
        {
            Exec(db, isPg
                ? "ALTER TABLE \"LlmConfigs\" ADD COLUMN \"Name\" character varying(200) NOT NULL DEFAULT ''"
                : "ALTER TABLE \"LlmConfigs\" ADD COLUMN \"Name\" TEXT NOT NULL DEFAULT ''");
        }
        if (!ColumnExists(db, "LlmConfigs", "IsDefault"))
        {
            Exec(db, isPg
                ? "ALTER TABLE \"LlmConfigs\" ADD COLUMN \"IsDefault\" boolean NOT NULL DEFAULT FALSE"
                : "ALTER TABLE \"LlmConfigs\" ADD COLUMN \"IsDefault\" INTEGER NOT NULL DEFAULT 0");
        }
        if (!ColumnExists(db, "LlmConfigs", "Protocol"))
        {
            Exec(db, isPg
                ? "ALTER TABLE \"LlmConfigs\" ADD COLUMN \"Protocol\" character varying(20) NOT NULL DEFAULT 'openai'"
                : "ALTER TABLE \"LlmConfigs\" ADD COLUMN \"Protocol\" TEXT NOT NULL DEFAULT 'openai'");
        }
        if (!ColumnExists(db, "LlmConfigs", "ModelsJson"))
        {
            Exec(db, isPg
                ? "ALTER TABLE \"LlmConfigs\" ADD COLUMN \"ModelsJson\" text NOT NULL DEFAULT ''"
                : "ALTER TABLE \"LlmConfigs\" ADD COLUMN \"ModelsJson\" TEXT NOT NULL DEFAULT ''");
        }

        if (!ColumnExists(db, "LlmConfigs", "RetryPolicy"))
        {
            Exec(db, isPg
                ? "ALTER TABLE \"LlmConfigs\" ADD COLUMN \"RetryPolicy\" character varying(20) NOT NULL DEFAULT 'default'"
                : "ALTER TABLE \"LlmConfigs\" ADD COLUMN \"RetryPolicy\" TEXT NOT NULL DEFAULT 'default'");
        }
        if (!ColumnExists(db, "LlmConfigs", "MaxRetries"))
        {
            Exec(db, isPg
                ? "ALTER TABLE \"LlmConfigs\" ADD COLUMN \"MaxRetries\" integer NOT NULL DEFAULT 8"
                : "ALTER TABLE \"LlmConfigs\" ADD COLUMN \"MaxRetries\" INTEGER NOT NULL DEFAULT 8");
        }
        if (!ColumnExists(db, "LlmConfigs", "RetryOn"))
        {
            Exec(db, isPg
                ? "ALTER TABLE \"LlmConfigs\" ADD COLUMN \"RetryOn\" text NOT NULL DEFAULT 'empty,rate_limit,server,timeout,network'"
                : "ALTER TABLE \"LlmConfigs\" ADD COLUMN \"RetryOn\" TEXT NOT NULL DEFAULT 'empty,rate_limit,server,timeout,network'");
        }

        // 历史配置补一个可读名字
        Exec(db, isPg
            ? "UPDATE \"LlmConfigs\" SET \"Name\" = '默认配置' WHERE \"Name\" = ''"
            : "UPDATE \"LlmConfigs\" SET \"Name\" = '默认配置' WHERE \"Name\" = ''");

        // 历史单模型配置回填模型清单：老库只存了 Model，不补的话前端模型列表是空的
        Exec(db, isPg
            ? "UPDATE \"LlmConfigs\" SET \"ModelsJson\" = '[\"' || \"Model\" || '\"]' WHERE \"ModelsJson\" = '' AND \"Model\" <> ''"
            : "UPDATE \"LlmConfigs\" SET \"ModelsJson\" = '[\"' || \"Model\" || '\"]' WHERE \"ModelsJson\" = '' AND \"Model\" <> ''");

        // 没有任何默认项时，把最早的一条设为默认（保证 GetConfig 有稳定结果）
        var configs = db.LlmConfigs.OrderBy(x => x.Id).ToList();
        if (configs.Count > 0 && configs.All(x => !x.IsDefault))
        {
            var first = configs.FirstOrDefault(x => x.IsConfigured) ?? configs[0];
            first.IsDefault = true;
            db.SaveChanges();
            logger?.LogInformation("已将 LLM 配置 Id={Id} 设为默认", first.Id);
        }
    }

    private static void Exec(AppDbContext db, string sql) => db.Database.ExecuteSqlRaw(sql);

    /// <summary>加列；若列已存在（42701 / duplicate column）则视为成功，保证可重复执行。</summary>
    private static void TryAddLibraryColumn(AppDbContext db, string sql)
    {
        try
        {
            db.Database.ExecuteSqlRaw(sql);
        }
        catch (Exception ex) when (IsDuplicateColumn(ex))
        {
            // 列已存在，幂等忽略
        }
    }

    private static bool IsDuplicateColumn(Exception ex)
    {
        for (var e = ex; e is not null; e = e.InnerException)
        {
            if (e.Message.Contains("already exists", StringComparison.OrdinalIgnoreCase)
                || e.Message.Contains("duplicate column", StringComparison.OrdinalIgnoreCase))
                return true;
            // Npgsql PostgresException.SqlState == 42701（duplicate_column）
            var state = e.GetType().GetProperty("SqlState")?.GetValue(e) as string;
            if (state == "42701") return true;
        }
        return false;
    }

    private static bool ColumnExists(AppDbContext db, string table, string column)
    {
        var conn = db.Database.GetDbConnection();
        var wasClosed = conn.State != System.Data.ConnectionState.Open;
        if (wasClosed) conn.Open();
        try
        {
            using var cmd = conn.CreateCommand();
            var isPg = db.Database.ProviderName?.Contains("Npgsql", StringComparison.OrdinalIgnoreCase) == true;
            // PostgreSQL 标识符大小写敏感（EF 建表为 "Links"/"LibraryId"），必须用 lower() 比对
            cmd.CommandText = isPg
                ? "SELECT COUNT(*) FROM information_schema.columns WHERE lower(table_name) = lower(@t) AND lower(column_name) = lower(@c)"
                : $"PRAGMA table_info(\"{table}\")";
            if (isPg)
            {
                var pt = cmd.CreateParameter(); pt.ParameterName = "@t"; pt.Value = table; cmd.Parameters.Add(pt);
                var pc = cmd.CreateParameter(); pc.ParameterName = "@c"; pc.Value = column; cmd.Parameters.Add(pc);
                var n = Convert.ToInt64(cmd.ExecuteScalar());
                return n > 0;
            }
            using var reader = cmd.ExecuteReader();
            while (reader.Read())
            {
                // PRAGMA table_info 第 2 列是列名
                if (string.Equals(reader.GetString(1), column, StringComparison.OrdinalIgnoreCase)) return true;
            }
            return false;
        }
        finally
        {
            if (wasClosed) conn.Close();
        }
    }
}
